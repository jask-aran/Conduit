import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, copyFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const scratch = path.resolve(root, "../.smoke-tools/app-icons");
const source = readFileSync(path.join(root, "public/favicon.svg"), "utf8");
const background = source.match(/<rect\b[^>]*\bfill="([^"]+)"/)[1];
const foreground = source.match(/<path\b[^>]*\bfill="([^"]+)"/)[1];
const mark = source.match(/<path\b[^>]*\bd="([^"]+)"/)[1];
const save = (file, content) => {
  const destination = path.join(root, file);
  mkdirSync(path.dirname(destination), { recursive: true });
  writeFileSync(destination, content);
};

// Windows needs ICO resources; keep just one PNG for Tauri's portable fallback.
for (const dev of [false, true]) {
  const input = path.join(scratch, dev ? "dev.svg" : "release.svg");
  const output = path.join(scratch, dev ? "dev" : "release");
  mkdirSync(scratch, { recursive: true });
  writeFileSync(input, dev ? source.replace(new RegExp(`${background}|${foreground}`, "g"), (color) => color === background ? foreground : background) : source);
  execFileSync("npx", ["--no-install", "tauri", "icon", input, "--output", output], { cwd: root, stdio: "inherit" });
  const destination = path.join(root, "src-tauri/icons", dev ? "dev" : "");
  mkdirSync(destination, { recursive: true });
  copyFileSync(path.join(output, "icon.ico"), path.join(destination, "icon.ico"));
  copyFileSync(path.join(output, "128x128.png"), path.join(destination, "icon.png"));
  save(`android/app/src/${dev ? "debug" : "main"}/res/values/ic_launcher_background.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by npm run icons:generate from public/favicon.svg. -->
<resources>
    <color name="ic_launcher_background">${dev ? foreground : background}</color>
    <color name="ic_launcher_foreground_color">${dev ? background : foreground}</color>
${dev ? "" : `    <color name="conduit_frame">${background}</color>\n`}</resources>
`);
}

const vector = (size, x, y, scale, fill = "") => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by npm run icons:generate from public/favicon.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size === 24 ? 48 : size}dp" android:height="${size === 24 ? 48 : size}dp"
    android:viewportWidth="${size}" android:viewportHeight="${size}">
${fill}    <group android:translateX="${x}" android:translateY="${y}" android:scaleX="${scale}" android:scaleY="${scale}">
        <path android:fillColor="@color/ic_launcher_foreground_color" android:pathData="${mark}" />
    </group>
</vector>
`;
// Adaptive foreground/splash, plus a vector fallback for supported API 24–25.
save("android/app/src/main/res/drawable/ic_launcher_foreground.xml", vector(108, 30, 38.12, 0.04103));
save("android/app/src/main/res/mipmap-anydpi/ic_launcher.xml", vector(24, 5, 7.4, 14 / 1170,
  '    <path android:fillColor="@color/ic_launcher_background" android:pathData="M5.5,0 H18.5 A5.5,5.5 0 0,1 24,5.5 V18.5 A5.5,5.5 0 0,1 18.5,24 H5.5 A5.5,5.5 0 0,1 0,18.5 V5.5 A5.5,5.5 0 0,1 5.5,0 Z" />\n'));
save("android/app/src/main/res/mipmap-anydpi/ic_launcher_round.xml", `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by npm run icons:generate; adaptive round icons remain in v26. -->
<inset xmlns:android="http://schemas.android.com/apk/res/android" android:drawable="@mipmap/ic_launcher" />
`);
