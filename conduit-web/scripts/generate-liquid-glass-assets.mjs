import fs from "node:fs";
import path from "node:path";
import { deflateSync } from "node:zlib";
import { createLiquidGlassAsset } from "../src/client/chat/liquid-glass-generator.mjs";
import {
  LIQUID_GLASS_FAMILIES,
  LIQUID_GLASS_HEIGHT_BUCKETS,
  LIQUID_GLASS_REFRACTIVE_INDEX,
  LIQUID_GLASS_SCALE_RATIO,
  LIQUID_GLASS_THICKNESS,
} from "../src/client/chat/liquid-glass-static.ts";

const outputDir = path.resolve(import.meta.dirname, "../public/glass");
const constantsPath = path.resolve(import.meta.dirname, "../src/client/chat/liquid-glass-constants.ts");
const geometryCssPath = path.resolve(import.meta.dirname, "../src/client/chat/composer-geometry.css");
const families = Object.values(LIQUID_GLASS_FAMILIES);
const heights = LIQUID_GLASS_HEIGHT_BUCKETS;
const generatedAssetPattern = /^composer-[a-z0-9-]+-\d+(?:-specular)?\.png$/;

function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const typeBytes = Buffer.from(type, "ascii");
  const output = Buffer.alloc(12 + data.length);
  output.writeUInt32BE(data.length, 0);
  typeBytes.copy(output, 4);
  data.copy(output, 8);
  output.writeUInt32BE(crc32(Buffer.concat([typeBytes, data])), 8 + data.length);
  return output;
}

function encodePng(image) {
  const rowLength = image.width * 4;
  const raw = Buffer.alloc((rowLength + 1) * image.height);
  for (let row = 0; row < image.height; row += 1) {
    const offset = row * (rowLength + 1);
    raw[offset] = 0;
    Buffer.from(image.data.buffer, image.data.byteOffset + row * rowLength, rowLength).copy(raw, offset + 1);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(image.width, 0);
  header.writeUInt32BE(image.height, 4);
  header[8] = 8;
  header[9] = 6;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk("IHDR", header),
    pngChunk("IDAT", deflateSync(raw, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

fs.mkdirSync(outputDir, { recursive: true });
for (const entry of fs.readdirSync(outputDir, { withFileTypes: true })) {
  if (entry.isFile() && generatedAssetPattern.test(entry.name)) {
    fs.unlinkSync(path.join(outputDir, entry.name));
  }
}
const scales = {};
let count = 0;
for (const family of families) {
  for (const height of heights) {
    const asset = createLiquidGlassAsset({
      ...family,
      height,
      glassThickness: LIQUID_GLASS_THICKNESS,
      refractiveIndex: LIQUID_GLASS_REFRACTIVE_INDEX,
      dpr: 1,
    });
    fs.writeFileSync(path.join(outputDir, `composer-${family.name}-${height}.png`), encodePng(asset.displacement));
    fs.writeFileSync(path.join(outputDir, `composer-${family.name}-${height}-specular.png`), encodePng(asset.specular));
    scales[`${family.name}:${height}`] = asset.maxDisplacement * LIQUID_GLASS_SCALE_RATIO;
    count += 2;
  }
}
fs.writeFileSync(constantsPath, `export const LIQUID_GLASS_DISPLACEMENT_SCALES = ${JSON.stringify(scales, null, 2)} as const;\n`);
const desktop = LIQUID_GLASS_FAMILIES.desktop;
const mobile = LIQUID_GLASS_FAMILIES.mobile;
fs.writeFileSync(geometryCssPath, `/* Generated by scripts/generate-liquid-glass-assets.mjs. Do not edit. */
:root {
  --composer-desktop-reference-width: ${desktop.width}px;
  --composer-mobile-reference-width: ${mobile.width}px;
  --composer-radius: ${desktop.radius}px;
}

@media (--conduit-mobile-layout) {
  :root {
    --composer-radius: ${mobile.radius}px;
  }
}
`);
const expectedMaps = families.length * heights.length * 2;
if (count !== expectedMaps) throw new Error(`Generated ${count} Liquid Glass maps; expected ${expectedMaps}.`);
console.log(`Generated ${count} liquid-glass maps at ${outputDir}`);

