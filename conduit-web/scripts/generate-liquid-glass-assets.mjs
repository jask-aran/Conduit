import fs from "node:fs";
import path from "node:path";
import { deflateSync } from "node:zlib";
import { createLiquidGlassAsset } from "../src/client/chat/liquid-glass-generator.mjs";

const outputPath = path.resolve(import.meta.dirname, "../src/client/chat/liquid-glass-static.ts");
const variants = [
  { name: "desktopEmpty", width: 700, height: 81, radius: 23, dpr: 1 },
  { name: "desktopEmptyRetina", width: 700, height: 81, radius: 23, dpr: 2 },
  { name: "desktop", width: 756, height: 81, radius: 23, dpr: 1 },
  { name: "desktopRetina", width: 756, height: 81, radius: 23, dpr: 2 },
  { name: "mobile", width: 384, height: 42, radius: 17, dpr: 1 },
  { name: "mobileRetina", width: 384, height: 42, radius: 17, dpr: 2.625 },
];

function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const typeBytes = Buffer.from(type, "ascii");
  const output = Buffer.alloc(12 + data.length);
  output.writeUInt32BE(data.length, 0);
  typeBytes.copy(output, 4);
  data.copy(output, 8);
  output.writeUInt32BE(crc32(Buffer.concat([typeBytes, data])), 8 + data.length);
  return output;
}

function encodePng(image) {
  const rowLength = image.width * 4;
  const raw = Buffer.alloc((rowLength + 1) * image.height);
  for (let row = 0; row < image.height; row += 1) {
    const offset = row * (rowLength + 1);
    raw[offset] = 0;
    Buffer.from(image.data.buffer, image.data.byteOffset + row * rowLength, rowLength).copy(raw, offset + 1);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(image.width, 0);
  header.writeUInt32BE(image.height, 4);
  header[8] = 8;
  header[9] = 6;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk("IHDR", header),
    pngChunk("IDAT", deflateSync(raw, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

function dataUrl(image) {
  return `data:image/png;base64,${encodePng(image).toString("base64")}`;
}

const assets = variants.map((variant) => {
  const asset = createLiquidGlassAsset({ ...variant, bezelWidth: 4, glassThickness: 70, refractiveIndex: 1.5 });
  return {
    ...variant,
    key: asset.key,
    mapWidth: asset.displacement.width,
    mapHeight: asset.displacement.height,
    maxDisplacement: asset.maxDisplacement,
    displacementUrl: dataUrl(asset.displacement),
    specularUrl: dataUrl(asset.specular),
  };
});

const source = `// Generated by scripts/generate-liquid-glass-assets.mjs.\n// Do not edit the data URLs by hand.\nexport interface LiquidGlassStaticAsset {\n  name: string;\n  key: string;\n  width: number;\n  height: number;\n  radius: number;\n  dpr: number;\n  mapWidth: number;\n  mapHeight: number;\n  maxDisplacement: number;\n  displacementUrl: string;\n  specularUrl: string;\n}\n\nexport const LIQUID_GLASS_STATIC_ASSETS: readonly LiquidGlassStaticAsset[] = ${JSON.stringify(assets, null, 2)};\n`;
fs.writeFileSync(outputPath, source);
console.log(`Generated ${assets.length} liquid-glass asset variants at ${outputPath}`);
