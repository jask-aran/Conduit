#!/usr/bin/env node
// Run from any directory: node conduit-web/scripts/generate-android-glyphs.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';

const root = new URL('../', import.meta.url);
const read = (path) => readFile(new URL(path, root), 'utf8');
const required = (source, pattern) => {
  const match = source.match(pattern);
  assert(match, `Source format changed: ${pattern}`);
  return match[1];
};
const appearance = await read('src/client/project/workspace-appearance.tsx');
const options = required(appearance, /WORKSPACE_ICON_OPTIONS = \[([\s\S]*?)\] as const/);
const workspaceIds = [...options.matchAll(/id: "([\w-]+)"/g)].map((match) => match[1]);
assert(workspaceIds.includes('boxes'));
const ids = [...new Set([...workspaceIds, 'folder', 'search'])];
const header = 'Generated by conduit-web/scripts/generate-android-glyphs.mjs. Do not edit.';
const drawableRoot = new URL('android/app/src/main/res/drawable/', root);
await mkdir(drawableRoot, { recursive: true });

// SVG arcs preserve circles, ellipses and rounded rectangle corners without cubic approximations.
function pathData(type, a) {
  switch (type) {
    case 'path': return a.d;
    case 'line': return `M${a.x1},${a.y1}L${a.x2},${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const points = a.points.trim().split(/[\s,]+/).map(Number);
      assert(points.length >= 2 && points.length % 2 === 0 && points.every(Number.isFinite));
      return `M${points[0]},${points[1]}` + points.slice(2).reduce((path, n, i, rest) =>
        i % 2 === 0 ? path + `L${n},${rest[i + 1]}` : path, '') + (type === 'polygon' ? 'Z' : '');
    }
    case 'circle':
    case 'ellipse': {
      const cx = Number(a.cx ?? 0), cy = Number(a.cy ?? 0);
      const rx = Number(a.r ?? a.rx), ry = Number(a.r ?? a.ry);
      return `M${cx - rx},${cy}A${rx},${ry} 0 1,0 ${cx + rx},${cy}A${rx},${ry} 0 1,0 ${cx - rx},${cy}Z`;
    }
    case 'rect': {
      const x = Number(a.x ?? 0), y = Number(a.y ?? 0), w = Number(a.width), h = Number(a.height);
      const rx = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2);
      const ry = Math.min(Number(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx || !ry) return `M${x},${y}H${x + w}V${y + h}H${x}Z`;
      return `M${x + rx},${y}H${x + w - rx}A${rx},${ry} 0 0,1 ${x + w},${y + ry}` +
        `V${y + h - ry}A${rx},${ry} 0 0,1 ${x + w - rx},${y + h}` +
        `H${x + rx}A${rx},${ry} 0 0,1 ${x},${y + h - ry}` +
        `V${y + ry}A${rx},${ry} 0 0,1 ${x + rx},${y}Z`;
    }
    default: throw new Error(`Unsupported lucide element: ${type}`);
  }
}
const xml = (value) => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
const elementTypes = new Set();
const resource = (id) => `glyph_${id.replaceAll('-', '_')}`;
for (const id of ids) {
  const source = await read(`node_modules/lucide-solid/dist/esm/icons/${id}.mjs`);
  // Evaluate only the installed package's literal node array, without importing its Solid runtime.
  const nodes = runInNewContext(required(source, /const iconNode = ([\s\S]*?);\s/), Object.create(null), { timeout: 1000 });
  assert(Array.isArray(nodes) && nodes.length > 0, `No nodes for ${id}`);
  const paths = nodes.map(([type, attributes]) => {
    elementTypes.add(type);
    // The requested Android style has no fill, including Lucide's filled palette dots.
    assert(attributes.fill == null || attributes.fill === 'currentColor', `Unsupported fill in ${id}`);
    assert(Object.keys(attributes).every((key) => ['key', 'fill', 'd', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'x2', 'y1', 'y2', 'points'].includes(key)), `Unsupported attributes in ${id}`);
    const d = pathData(type, attributes);
    assert(d && !/NaN|undefined|Infinity/.test(d), `Invalid path for ${id}`);
    return `    <path android:pathData="${xml(d)}" android:strokeColor="#ffffff" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />`;
  });
  await writeFile(new URL(`${resource(id)}.xml`, drawableRoot), `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${header} -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="16dp" android:height="16dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths.join('\n')}\n</vector>\n`);
}

const palettes = await read('src/components/ui/palettes.ts');
const hues = [...required(palettes, /IDENTITY_HUES = \[([^\]]+)\]/).matchAll(/"([\w-]+)"/g)].map((m) => m[1]);
const identity = required(palettes, /const IDENTITY = \{([\s\S]*?)satisfies/);
const paletteName = required(identity, /palette: (\w+)/);
const paletteId = required(palettes, new RegExp(`const ${paletteName}: Palette = \\{ id: "([\\w-]+)"`));
const mappings = new Map([...required(identity, /hues: \{([\s\S]*)/).matchAll(/(\w+): "([\w-]+)"/g)].map((m) => [m[1], m[2]]));
const css = await read('src/components/ui/styles/palettes.css');
const colours = hues.map((hue) => {
  assert(mappings.has(hue), `Missing identity hue: ${hue}`);
  const value = required(css, new RegExp(`--${paletteId}-${mappings.get(hue)}:\\s*([^;]+);`)).trim();
  // Current identity CSS is already sRGB. Fail if the palette changes to a different colour space.
  assert(/^#[\da-f]{6}$/i.test(value), `Expected sRGB hex for ${hue}: ${value}`);
  return [hue, `0xFF${value.slice(1).toUpperCase()}`];
});
const aliases = [...mappings].filter(([hue, name]) => !hues.includes(name));
const java = `// ${header}
package com.jaskaran.conduit;

public final class FloatGlyphs {
    private FloatGlyphs() {}

    public static int icon(String id) {
        switch (id == null ? "" : id) {
${ids.map((id) => `            case "${id}": return R.drawable.${resource(id)};`).join('\n')}
            default: return R.drawable.glyph_boxes;
        }
    }

    static String iconId(String id) {
        switch (id == null ? "" : id) {
${workspaceIds.map((id) => `            case "${id}":`).join('\n')}
                return id;
            default: return "boxes";
        }
    }

    static String colourId(String id) {
        String value = trim(id).toLowerCase(java.util.Locale.ROOT);
        switch (value) {
${hues.map((hue) => `            case "${hue}":`).join('\n')}
                return value;
${aliases.map(([hue, name]) => `            case "${name}": return "${hue}";`).join('\n')}
            default: return value.matches("#[0-9a-f]{6}") ? value : "violet";
        }
    }

    // Match JavaScript String.trim(), including non-ASCII whitespace.
    static String trim(String value) {
        return value == null ? "" : value.replaceAll("^[\\\\s\\\\p{Zs}\\\\u2028\\\\u2029\\\\uFEFF]+|[\\\\s\\\\p{Zs}\\\\u2028\\\\u2029\\\\uFEFF]+$", "");
    }

    public static int colour(String colourId) {
        String id = colourId(colourId);
        switch (id) {
${colours.map(([hue, argb]) => `            case "${hue}": return ${argb};`).join('\n')}
            default: return (int) (0xFF000000L | Long.parseLong(id.substring(1), 16));
        }
    }
}
`;
await writeFile(new URL('android/app/src/main/java/com/jaskaran/conduit/FloatGlyphs.java', root), java);
console.log(`Generated ${ids.length} icons (${workspaceIds.length} workspace + folder/search); elements: ${[...elementTypes].sort().join(', ')}`);
console.log(colours.map(([hue, argb]) => `${hue}: ${argb}`).join('\n'));
