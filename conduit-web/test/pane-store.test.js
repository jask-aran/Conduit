import assert from "node:assert/strict";
import test from "node:test";
import * as panes from "../src/client/panes/pane-store.ts";

test("pane verbs keep documents unique, drafts held, tabs recent, and summons over the dock", () => {
  let layout = panes.layoutOf("chat:one");
  const main = layout.focus;
  layout = panes.open(layout, "chat:two", { tab: true });
  layout = panes.open(layout, "artifact:paper", { beside: true });
  const paper = layout.row[1];
  assert.equal(layout.focus, main, "Alt keeps the keyboard");
  layout = panes.open(panes.focus(layout, paper), "chat:three", { tab: true });
  assert.equal(layout.focus, main, "Ctrl from a document joins the session");
  layout = panes.switchTab(layout, main, 0);
  layout = panes.closeTab(layout, main, 0);
  assert.equal(panes.shownView(layout.panes[main]), "chat:three", "closing returns to the last shown tab");
  layout = panes.moveToDock(layout, paper);
  const summoned = panes.summon(layout, "files");
  assert.equal(summoned.dock, paper);
  assert.equal(panes.summon(summoned, "files").summon, null);
  const restored = panes.decode(panes.encode(summoned), value => typeof value === "string");
  assert.equal(panes.encode(restored).toString(), panes.encode(summoned).toString());
  layout = panes.open(summoned, "artifact:paper");
  assert.equal(Object.keys(layout.panes).length, 2, "opening an existing document goes to it");
  assert.equal(layout.focus, paper);
  let tabs = panes.layoutOf("chat:held");
  for (let i = 0; i < panes.TAB_CAP + 2; i++) tabs = panes.open(tabs, `chat:${i}`, { tab: true }, { held: view => view === "chat:held" });
  assert.equal(tabs.panes[tabs.focus].views.length, panes.TAB_CAP);
  assert.equal(tabs.panes[tabs.focus].views.includes("chat:held"), true);
  tabs = panes.decode(panes.encode(tabs), value => typeof value === "string");
  tabs = panes.switchTab(tabs, tabs.focus, 1);
  const revisited = panes.shownView(tabs.panes[tabs.focus]);
  tabs = panes.switchTab(tabs, tabs.focus, 2);
  tabs = panes.open(tabs, "chat:new", { tab: true }, { held: view => view === "chat:held" });
  assert.equal(tabs.panes[tabs.focus].views.includes(revisited), true, "a revisited tab is kept over an older one");
  const store = panes.createPaneStore(layout);
  store.apply(current => panes.moveToRow(current, paper));
  assert.equal(store.layout().dock, null);
  store.undo();
  assert.equal(store.layout(), layout);
  store.redo();
  assert.equal(store.layout().row.includes(paper), true);
});
